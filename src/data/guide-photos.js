function caption(file, artist) {
  let c = file.replace(/\.(jpe?g)$/i, '');
  if (artist) c = c.split(artist).join('');
  c = c
    .replace(/\s*\(\d+\)\s*$/g, '')
    .replace(/\s*\(edit\)/i, '')
    .replace(/[\s\-_,~]*\d{3,}[\s\d\-_]*$/g, '')
    .replace(/\s+\d{1,2}$/g, '')
    .replace(/[\s\-,]+$/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
  return c.length > 90 ? c.slice(0, 87).replace(/\s+\S*$/, '') + '...' : c;
}

